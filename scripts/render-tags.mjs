// 按 index.json 生成 TAGS.md:词表的唯一来源是 index.json,TAGS.md 不手改。
// TAGS.md 是给扩展作者的 coding agent 看的,只写英文;标签名与悬停说明的中文只进 WebUI。
import { writeFileSync } from 'node:fs';
import { loadIndex, readJson, root } from './lib.mjs';

const index = loadIndex();
const EXAMPLES = 4;

// 例子取 Action 合并后的标签;还没有 catalog.json 时退回 index.json 的 addTags。
const catalog = readJson('catalog.json');
const tagsOf = catalog
  ? Object.entries(catalog.packages).map(([name, p]) => [name, p.tags])
  : Object.entries(index.overrides).map(([name, o]) => [name, o.addTags ?? []]);
const examples = (id) => tagsOf.filter(([, tags]) => tags.includes(id)).map(([name]) => `\`${name}\``);

const row = (id, t) => {
  const ex = examples(id);
  const shown = ex.slice(0, EXAMPLES).join(' ') + (ex.length > EXAMPLES ? ` and ${ex.length - EXAMPLES} more` : '');
  return `| \`${id}\` | ${t.label.en} | ${t.when} | ${t.hint.en.replace(/\n/g, '<br>')} | ${shown || '—'} |`;
};

const entries = Object.entries(index.tags);
const official = entries.filter(([, t]) => t.style === 'official');
const author = entries.filter(([, t]) => !t.style);
const notice = entries.filter(([, t]) => t.style === 'notice');
const warning = entries.filter(([, t]) => t.style === 'warning');
const head = '| id | Label | When to use | Hover hint shown to users | Existing examples |\n|---|---|---|---|---|';

const md = `<!-- Generated by scripts/render-tags.mjs from index.json. Do not edit by hand. -->

# Cortico extension tags

Pick every tag below that fits and list it in \`cortico.tags\` in package.json. The WebUI market groups and filters extensions by these tags and shows the hover hint to users.

\`\`\`jsonc
"cortico": { "kind": "world", "api": 5, "tags": ["im", "qq", "companion"] }
\`\`\`

## Not accepted in the market

An extension whose features or bundled content fall into any category below is blocked as soon as it reaches the market, with no warning first. An author blocked twice for the same category has their npm and GitHub accounts blocked permanently, which removes every package they publish.

1. **Model jailbreaks**: prompts, personas or tooling meant to get a model past its provider's safety rules.
2. **NSFW**: sexual content, or features for generating it.
3. **Security attacks and reverse engineering**: letting the bot scan or attack systems, write or run exploits or malware, crack license checks or DRM, or unpack and decompile software.
4. **Tracking third parties**: collecting, linking or keeping personal information about specific people other than the user, to profile, locate or monitor them, such as doxxing, matching someone's accounts across platforms, or covertly logging their chats. The chat context and memories a bot keeps for its own conversations do not count.
5. **Malicious code and impersonation**: stealing credentials, mining, backdoors, sending data out without telling the user, or posing as Pal AI Lab, Cortico or Coopanion.
6. **Cheats for online multiplayer games**: reading or writing game memory, injecting code or tampering with traffic to gain an unfair edge over other players.
7. **Spam and bulk automation**: mass messaging, fake likes, views or follows, or running batches of accounts.
8. **Content illegal in China**: political content, gambling, fraud.

## How to choose

- Choose by **what the extension connects to and what it lets the bot do**, not by how it is built. Calling an HTTP API is not \`browser\`; connecting to QQ is \`qq\`.
- An add-on pack for another extension carries its host's platform tag (QQ add-ons carry \`qq\`).
- Tag only what truly fits, not to appear in more filters. Use \`apps\` only when no other tag fits. If nothing fits, leave it empty and maintainers will correct it.
- Platform limits go in the standard npm \`"os"\` field (\`["win32"]\`, or \`["!darwin"]\` to exclude), not in tags.
- Notice and warning tags count only when listed in \`cortico.tags\`; \`keywords\` map to plain tags only.
- Run \`pnpm check:extension <dir>\` afterwards; tags outside this list are reported.

## Who adds and removes

| Level | Author | Maintainers |
|---|---|---|
| Official mark (blue) | cannot declare; ignored if listed | add and remove |
| Plain | add and remove | add and remove |
| Notice (yellow) | add; remove only what the author added | add and remove |
| Warning (red) | add; once any version declares it, it stays | add and remove |

Declare notice and warning tags yourself where they apply. Their absence means "not declared and not reviewed yet", not "safe".
To remove a tag added by maintainers, or withdraw a declared warning tag, open an issue in this repository titled \`[tags] package-name\`. The [README](README.md) gives the request format.

## Official marks

Blue marks for extensions used by an official Cortico downstream product. Only maintainers assign them. Do not list them in \`cortico.tags\`; they are ignored there.

${head}
${official.map(([id, t]) => row(id, t)).join('\n')}

## Plain tags

${head}
${author.map(([id, t]) => row(id, t)).join('\n')}

## Notice tags

${head}
${notice.map(([id, t]) => row(id, t)).join('\n')}

## Warning tags

${head}
${warning.map(([id, t]) => row(id, t)).join('\n')}

## Proposing a tag

Once at least 3 published extensions would use the tag, open an issue titled \`[new-tag] id\` or a PR against \`index.json\`. Give the label and hover hint in Chinese and English, and \`when\` in English.
`;

writeFileSync(`${root}TAGS.md`, md);
console.log(`TAGS.md: ${official.length} official, ${author.length} plain, ${notice.length} notice, ${warning.length} warning tags`);
