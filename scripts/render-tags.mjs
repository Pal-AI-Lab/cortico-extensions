// 按 index.json 生成 TAGS.md:词表的唯一来源是 index.json,TAGS.md 不手改。
// TAGS.md 是给扩展作者的 coding agent 看的,只写英文;标签名与悬停说明的中文只进控制台。
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const index = JSON.parse(readFileSync(`${root}index.json`, 'utf8'));
const EXAMPLES = 4;

const examples = (id) => Object.entries(index.overrides)
  .filter(([, o]) => o.addTags?.includes(id))
  .map(([name]) => `\`${name}\``);

const row = (id, t) => {
  const ex = examples(id);
  const shown = ex.slice(0, EXAMPLES).join(' ') + (ex.length > EXAMPLES ? ` and ${ex.length - EXAMPLES} more` : '');
  return `| \`${id}\` | ${t.label.en} | ${t.when} | ${t.hint.en} | ${shown || '—'} |`;
};

const entries = Object.entries(index.tags);
const official = entries.filter(([, t]) => t.style === 'official');
const author = entries.filter(([, t]) => !t.style);
const notice = entries.filter(([, t]) => t.style === 'notice');
const warning = entries.filter(([, t]) => t.style === 'warning');
const head = '| id | Label | When to use | Hover hint shown to users | Existing examples |\n|---|---|---|---|---|';

const md = `<!-- Generated by scripts/render-tags.mjs from index.json. Do not edit by hand. -->

# Cortico extension tags

Pick every tag below that fits and list it in \`cortico.tags\` in package.json. The console market groups and filters extensions by these tags and shows the hover hint to users.

\`\`\`jsonc
"cortico": { "kind": "world", "api": 5, "tags": ["im", "qq", "companion"] }
\`\`\`

## How to choose

- Choose by **what the extension connects to and what it lets the bot do**, not by how it is built. Calling an HTTP API is not \`browser\`; connecting to QQ is \`qq\`.
- An add-on pack for another extension carries its host's platform tag (QQ add-ons carry \`qq\`).
- Tag only what truly fits, not to appear in more filters. Use \`apps\` only when no other tag fits. If nothing fits, leave it empty and maintainers will correct it.
- Platform limits go in the standard npm \`"os"\` field (\`["win32"]\`, or \`["!darwin"]\` to exclude), not in tags.
- Notice and warning tags count only when listed in \`cortico.tags\`; \`keywords\` map to plain tags only.
- Run \`pnpm check:extension <dir>\` afterwards; tags outside this list are reported.

## Who adds and removes

| Level | Author | Maintainers |
|---|---|---|
| Official mark (blue) | cannot declare; ignored if listed | add and remove |
| Plain | add and remove | add and remove |
| Notice (yellow) | add; remove only what the author added | add and remove |
| Warning (red) | add; once any version declares it, it stays | add and remove |

Declare notice and warning tags yourself where they apply. Their absence means "not declared and not reviewed yet", not "safe".
To remove a tag added by maintainers, or withdraw a declared warning tag, open an issue in this repository titled \`[tags] package-name\`. The [README](README.md) gives the request format.

## Official marks

Blue marks that only maintainers assign. Do not list them in \`cortico.tags\`; they are ignored there.

${head}
${official.map(([id, t]) => row(id, t)).join('\n')}

## Plain tags

${head}
${author.map(([id, t]) => row(id, t)).join('\n')}

## Notice tags

${head}
${notice.map(([id, t]) => row(id, t)).join('\n')}

## Warning tags

${head}
${warning.map(([id, t]) => row(id, t)).join('\n')}

## Proposing a tag

Once at least 3 published extensions would use the tag, open an issue titled \`[new-tag] id\` or a PR against \`index.json\`. Give the label and hover hint in Chinese and English, and \`when\` in English.
`;

writeFileSync(`${root}TAGS.md`, md);
console.log(`TAGS.md: ${official.length} official, ${author.length} plain, ${notice.length} notice, ${warning.length} warning tags`);
